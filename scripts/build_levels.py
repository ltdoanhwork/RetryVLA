#!/usr/bin/env python3
"""Build L1-L4 level maps for our LIBERO-Recover scenes from the OFFICIAL LIBERO-Recovery v1.0.0 annotations.

Upstream (github liulin815/LIBERO-Recovery @ 832d54d, 2026-10-22) released per-scene level annotations in the ModelScope
dataset `ataier/LIBERO_Recovery_FailureScenes` (`annotations/scenes/<suite>/<scene_id>.json`; Qwen3-VL-27B two-pass
annotation, "minimum intervention needed to resume the task"):
  L1 Action Retry | L2 Action Adaptation | L3 Object State Recovery (task object dropped / tipped / out of workspace)
  | L4 Environmental Recovery (remove an unrelated obstruction).
Our curated scenes (`LIBERO_Recovery_Assets`, `selected_bddl_scenes_<suite>`) are a subset of the same rollout dumps:
for matched scenes the `_sim_state.npy` is bit-identical (checked 2026-11-01 on 2 spatial + 2 object scenes).

Coverage: spatial 84 / 168 scenes exact (all `step_0180`; `step_0200` is not annotated upstream), object 50 / 77 exact
(`step_0240`; `step_0260` not annotated). Unannotated scenes INHERIT the label of the nearest annotated step of the same
failure episode (always 20 steps earlier), with `src: inherited`. This is weak: the VLM label of one episode changes
between annotated steps 60 steps apart in 45% (spatial 120->180) / 28% (object 160->240) of episodes, so report
per-level numbers on the `official` subset first and the inherited ones only as a secondary view.

usage: python scripts/build_levels.py   # (re)downloads missing annotations, writes configs/env/levels_{spatial,object}.yaml
"""

from __future__ import annotations

import concurrent.futures as cf
import glob
import json
import os
import re
import urllib.parse
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ANN = REPO / "data/assets/levels/annotations"
MS = "https://www.modelscope.cn/api/v1/datasets/ataier/LIBERO_Recovery_FailureScenes/repo"
SUITES = {"spatial": "data/splits/spatial_v1.json", "object": "data/splits/object_v1.json"}


def _ls(root: str) -> list[str]:
    out, page = [], 1
    while True:
        url = f"{MS}/tree?Revision=master&Recursive=false&PageSize=1000&PageNumber={page}&Root={urllib.parse.quote(root)}"
        files = json.load(urllib.request.urlopen(url))["Data"]["Files"]
        out += [f["Path"] for f in files if f["Type"] == "blob"]
        if len(files) < 1000:
            return out
        page += 1


def _get(path: str) -> None:
    dst = ANN / path.split("annotations/scenes/")[1]
    if dst.exists():
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    data = urllib.request.urlopen(f"{MS}?Revision=master&FilePath={urllib.parse.quote(path)}").read()
    json.loads(data)
    tmp = dst.with_suffix(".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, dst)


def download(suite: str) -> None:
    names = _ls(f"annotations/scenes/libero_{suite}")
    with cf.ThreadPoolExecutor(16) as ex:
        list(ex.map(_get, names))


def build(suite: str) -> dict:
    by_ep: dict[tuple[str, str], dict[int, dict]] = {}
    for f in glob.glob(str(ANN / f"libero_{suite}/*.json")):
        a = json.load(open(f))
        if a["scene_id"].startswith("l4_injected"):  # constructed L4 scenes are not in our curated set
            continue
        m = re.match(rf"libero_{suite}__(.+)__(episode_\d+)__step(\d+)$", a["scene_id"])
        by_ep.setdefault((m.group(1), m.group(2)), {})[int(m.group(3))] = a
    split = json.loads((REPO / SUITES[suite]).read_text())
    out = {}
    for tag in sorted(set(split["train"]) | set(split["test"])):
        task, ep, st = tag.split("__")
        step = int(st.split("_")[1])
        d = by_ep.get((task, ep), {})
        if step in d:
            a, src = d[step], "official"
        elif d:
            near = min(d, key=lambda k: (abs(k - step), -k))
            a, src = d[near], f"inherited_step{near:04d}"
        else:
            continue
        out[tag] = {"level": a["level"], "src": src, "conf": a.get("level_confidence"),
                    "stage": a.get("stage"), "reason": (a.get("level_reason") or "")[:160]}
    return out


def main() -> None:
    import yaml

    for suite in SUITES:
        download(suite)
        lv = build(suite)
        path = REPO / f"configs/env/levels_{suite}.yaml"
        hdr = (f"# L1-L4 levels for LIBERO-Recover {suite} scenes. Generated by scripts/build_levels.py from the OFFICIAL\n"
               "# LIBERO-Recovery v1.0.0 annotations (ModelScope ataier/LIBERO_Recovery_FailureScenes, Qwen3-VL-27B).\n"
               "# src=official: exact scene annotated upstream (sim_state bit-identical); src=inherited_stepXXXX: not annotated\n"
               "# upstream, label copied from that step of the same failure episode (weak, see script docstring).\n")
        tmp = path.with_suffix(".tmp")
        tmp.write_text(hdr + yaml.safe_dump({"levels": lv}, sort_keys=True, width=200, allow_unicode=True))
        os.replace(tmp, path)
        from collections import Counter

        print(suite, len(lv), Counter((v["src"] == "official", v["level"]) for v in lv.values()))


if __name__ == "__main__":
    main()
